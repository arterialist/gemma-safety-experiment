"""Audit script to verify integrity of all saved JSON results and optional local checkpoints."""

import json
import math
import os
import sys
from typing import Any


def _check_finite(obj: Any, path: str = "root") -> list[str]:
    issues = []
    if isinstance(obj, float):
        if math.isnan(obj) or math.isinf(obj):
            issues.append(f"Non-finite float at {path}: {obj}")
    elif isinstance(obj, dict):
        for k, v in obj.items():
            issues.extend(_check_finite(v, f"{path}.{k}"))
    elif isinstance(obj, list):
        for idx, v in enumerate(obj):
            issues.extend(_check_finite(v, f"{path}[{idx}]"))
    return issues


def main() -> None:
    expected_jsons = [
        "results/project1_mech_interp.json",
        "results/project1_abliteration.json",
        "results/project1_gemma3_4b.json",
        "results/project2_latent_guard.json",
        "results/project3_sleeper_agent.json",
    ]
    failed = False
    print("=== JSON INTEGRITY AUDIT ===")
    for p in expected_jsons:
        if not os.path.exists(p):
            print(f"[MISSING] {p}")
            failed = True
            continue
        with open(p, "r", encoding="utf-8") as f:
            data = json.load(f)
        issues = _check_finite(data, p)
        if issues:
            failed = True
            status = f"ISSUES: {issues[:3]}"
        else:
            status = "OK"
        elapsed = data.get("elapsed_seconds", 0.0)
        print(f"[FOUND]   {p} ({elapsed:.1f}s) -> {status}")

    optional_artifacts = [
        "artifacts/gemma3_1b_activations_and_dirs.pt",
        "artifacts/gemma-3-1b-it-abliterated",
        "artifacts/gemma-3-4b-it-abliterated",
        "artifacts/gemma-3-1b-sleeper-lora",
    ]
    print("\n=== LOCAL CHECKPOINT ARTIFACTS (OPTIONAL / GENERATED BY SCRIPTS) ===")
    for a in optional_artifacts:
        if not os.path.exists(a):
            print(f"[SKIPPED] {a} (not generated locally; run scripts/run_project*.py to build)")
            continue
        if os.path.isdir(a):
            files = sorted(os.listdir(a))
            print(f"[DIR OK]  {a} ({len(files)} files: {', '.join(files[:6])})")
        else:
            mb = os.path.getsize(a) / (1024 * 1024)
            print(f"[FILE OK] {a} ({mb:.1f} MB)")

    if failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
